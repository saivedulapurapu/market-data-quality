"""Generate reports/DATA_PROFILE.md and reports/QUALITY_REPORT.md from the store.

Every number in both files is computed here from data/processed/mdq.duckdb.
"""
from __future__ import annotations

import json

import numpy as np
import pandas as pd

from mdq import config, dashboard_data as dd, scoring, store
from mdq.calendar import sessions


def _md(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    out = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
    for r in df.itertuples(index=False):
        out.append("| " + " | ".join("" if (isinstance(v, float) and np.isnan(v)) else str(v) for v in r) + " |")
    return "\n".join(out)


def profile(con) -> dict:
    p = store.read(con, """SELECT source_id, adjustment, count(*) AS rows,
                                  count(DISTINCT security_id) AS securities,
                                  min(date) AS first, max(date) AS last
                           FROM prices GROUP BY ALL ORDER BY 1, 2""")
    split = store.read(con, "SELECT security_id, source_id, date FROM prices WHERE adjustment='split'")
    lo, hi = split.date.min(), split.date.max()
    n_sess = len(sessions(lo, hi))
    cov = (split.groupby("source_id").size() / (n_sess * split.security_id.nunique()) * 100).round(3)
    ca = store.read(con, "SELECT action_type, count(*) AS n, count(DISTINCT security_id) AS securities "
                         "FROM corporate_actions GROUP BY 1 ORDER BY 1")
    splits = dd.corporate_actions(con, action_type="split").sort_values("ex_date")
    rc = store.read(con, "SELECT diff_bps FROM recon_comparison")
    a = rc.diff_bps.abs()
    vol = store.read(con, """SELECT n.volume / y.volume AS r FROM prices y JOIN prices n
                             USING (security_id, date, adjustment)
                             WHERE y.source_id='yahoo' AND n.source_id='nasdaq' AND adjustment='split'
                               AND y.volume > 0 AND n.volume > 0""")
    return {
        "price_table": p, "first": lo, "last": hi, "sessions": n_sess,
        "securities": int(split.security_id.nunique()), "coverage_pct": cov.to_dict(),
        "ca": ca, "splits": splits,
        "recon": {"days_compared": int(len(rc)), "median_abs_bps": float(a.median()),
                  "p99_abs_bps": float(a.quantile(0.99)), "max_abs_bps": float(a.max()),
                  "pct_exact_within_1bp": float((a <= 1).mean() * 100)},
        "volume_ratio": {"median": float(vol.r.median()), "p01": float(vol.r.quantile(0.01)),
                         "p99": float(vol.r.quantile(0.99))},
    }


def write_profile(con) -> str:
    pr = profile(con)
    sec = dd.securities(con)
    ex = sec.groupby(["exchange", "asset_class"]).size().reset_index(name="securities")
    pt = pr["price_table"].copy()
    pt["first"] = pt["first"].dt.date
    pt["last"] = pt["last"].dt.date
    spl = pr["splits"][["security_id", "ex_date", "ratio", "details"]].copy()
    spl["ex_date"] = spl["ex_date"].dt.date
    r = pr["recon"]
    md = f"""# Data profile

Generated by `python -m mdq reports` from `data/processed/mdq.duckdb`. The data is fetched
locally from the sources below, for personal research only, and is **not redistributed**: no
vendor data is committed to this repository.

## Scope

| Item | Value |
|---|---|
| Securities | {pr['securities']} (50 stocks + 2 ETFs) |
| Date range | {pr['first'].date()} to {pr['last'].date()} |
| NYSE sessions in range | {pr['sessions']:,} |
| Sources | yahoo (Yahoo Finance chart API), nasdaq (Nasdaq.com historical API) |
| Calendar | NYSE (`pandas_market_calendars`, XNYS) |

{_md(ex)}

## Rows by source and adjustment basis

`split` is the series as delivered (both vendors split-adjust). `raw` is the as-traded series
reconstructed from the declared splits.

{_md(pt)}

Coverage of expected security-sessions (split-adjusted series):
{', '.join(f'**{k}** {v:.3f}%' for k, v in pr['coverage_pct'].items())}.

## Corporate actions (from Yahoo)

{_md(pr['ca'])}

Splits in the window:

{_md(spl)}

## Cross-source agreement (close, split-adjusted)

| Metric | Value |
|---|---|
| Security-days compared | {r['days_compared']:,} |
| Median \\|diff\\| | {r['median_abs_bps']:.3f} bps |
| 99th percentile \\|diff\\| | {r['p99_abs_bps']:.2f} bps |
| Max \\|diff\\| | {r['max_abs_bps']:.1f} bps |
| Days within 1 bp | {r['pct_exact_within_1bp']:.2f}% |

Volume is reported but not reconciled. The median Nasdaq/Yahoo volume ratio is
{pr['volume_ratio']['median']:.4f} (1st–99th percentile {pr['volume_ratio']['p01']:.3f}–{pr['volume_ratio']['p99']:.3f}).
The two vendors use slightly different consolidated-volume definitions, so a volume check
would need a looser and separately justified tolerance.
"""
    (config.REPORTS_DIR / "DATA_PROFILE.md").write_text(md, encoding="utf-8")
    return md


def recon_episodes(con, gap: int = 3) -> pd.DataFrame:
    """Group close mismatches into episodes (runs separated by <= gap sessions)
    and characterise each: constant ratio (adjustment-basis difference) vs isolated."""
    m = store.read(con, """SELECT security_id, date, value AS diff_bps, source_id
                           FROM quality_issues WHERE check_name = 'recon_close_mismatch'
                           ORDER BY security_id, date""")
    if m.empty:
        return pd.DataFrame()
    rows = []
    for sec, g in m.groupby("security_id"):
        sess = sessions(g.date.min(), g.date.max())
        pos = sess.get_indexer(g.date)
        ep = np.cumsum(np.concatenate([[1], np.diff(pos) > gap]))
        for _, e in g.groupby(ep):
            rows.append({"security_id": sec, "start": e.date.min().date(), "end": e.date.max().date(),
                         "days": len(e), "median_bps": round(float(e.diff_bps.median()), 2),
                         "std_bps": round(float(e.diff_bps.std()), 2) if len(e) > 1 else 0.0,
                         "blamed_yahoo": int((e.source_id == "yahoo").sum()),
                         "blamed_nasdaq": int((e.source_id == "nasdaq").sum()),
                         "undetermined": int(e.source_id.isna().sum())})
    return pd.DataFrame(rows).sort_values("days", ascending=False).reset_index(drop=True)


def _ev(details: str) -> str:
    try:
        d = json.loads(details)
    except (TypeError, ValueError):
        return str(details)
    return ", ".join(f"{k}={v:.4g}" if isinstance(v, float) else f"{k}={v}" for k, v in d.items())


def write_quality(con) -> str:
    counts = dd.issue_counts(con, include_info=True)
    scores = store.read(con, "SELECT * FROM quality_scores")
    ds = scoring.dataset_score(scores)
    worst = dd.security_scores(con).head(8)
    worst["avg_score"] = worst["avg_score"].round(3)
    eps = recon_episodes(con)
    ca = dd.corporate_actions(con)
    split_ver = dd.split_verification(con)

    def ex(check, n=5, src=None):
        df = dd.issues(con, check_name=check)
        if src:
            df = df[df.source_id == src]
        df = df.head(n).copy()
        df["date"] = df["date"].dt.date
        df["evidence"] = df["details"].map(_ev)
        return df[["security_id", "date", "source_id", "severity", "evidence"]]

    # CMCSA-style constant-ratio episode linked to a corporate action right after it
    long_eps = eps[eps.days >= 20] if len(eps) else eps
    ca_links = []
    for e in long_eps.itertuples():
        nxt = ca[(ca.security_id == e.security_id) & (ca.ex_date > pd.Timestamp(e.end))].sort_values("ex_date").head(1)
        if len(nxt):
            n = nxt.iloc[0]
            yfac = 1 / n.ratio if n.action_type == "split" else np.nan
            ca_links.append({"security_id": e.security_id, "episode": f"{e.start} → {e.end}",
                             "days": e.days, "median diff (bps)": e.median_bps, "std (bps)": e.std_bps,
                             "next event": f"{n.action_type} {n.details or ''} on {n.ex_date.date()}",
                             "implied nasdaq ratio": round(n.ratio * (1 + e.median_bps / 1e4), 5)
                             if n.action_type == "split" else ""})
    ca_links = pd.DataFrame(ca_links)

    sv = split_ver.copy()
    sv["ex_date"] = sv["ex_date"].dt.date
    sv["adjusted_move"] = sv["adjusted_move"].round(4)
    sv["raw_move"] = sv["raw_move"].round(4)
    sv["expected_raw_move"] = (1 / sv["ratio"]).round(4)

    # isolated mismatches: both bars side by side as evidence
    iso_rows = []
    for e in (eps[eps.days <= 3].itertuples() if len(eps) else []):
        bars = store.read(con, """SELECT source_id, open, high, low, close FROM prices
                                  WHERE security_id = ? AND date = ? AND adjustment = 'split'
                                  ORDER BY source_id DESC""", [e.security_id, str(e.start)])
        iss = dd.issues(con, security_id=e.security_id, check_name="recon_close_mismatch")
        blame = json.loads(iss.details.iloc[0]).get("blame") if len(iss) else ""
        for b in bars.itertuples():
            iso_rows.append({"security_id": e.security_id, "date": e.start, "source": b.source_id,
                             "open": round(b.open, 2), "high": round(b.high, 2), "low": round(b.low, 2),
                             "close": round(b.close, 2), "diff (bps)": e.median_bps, "blame": blame})
    iso = pd.DataFrame(iso_rows)
    ohlc = dd.issues(con, check_name="ohlc_inconsistent")
    sec_ex = dd.securities(con).set_index("security_id")["exchange"]
    worst_day = ds["worst_day"]
    wd = ohlc[ohlc.date == pd.Timestamp(worst_day)] if worst_day else ohlc.iloc[0:0]
    wd_src = ", ".join(sorted(wd.source_id.unique()))
    wd_ex = wd.security_id.map(sec_ex).value_counts().to_dict()
    n_nyse = int((sec_ex == "NYSE").sum())
    long_ep = eps.iloc[0] if len(eps) else None
    scored = counts[counts.severity != "info"]
    info = counts[counts.severity == "info"]
    md = f"""# Quality report: real data

Generated by `python -m mdq reports` from the latest pipeline run, using the tuned default
parameters in `mdq/config.py`. Every issue below is a real finding in the real Yahoo and
Nasdaq data, not an injected one.

## Summary

| Metric | Value |
|---|---|
| Issues logged (all severities) | {int(counts.n.sum()):,} |
| Scored issues (severity ≥ warning) | {int(scored.n.sum()):,} |
| Info (corroborated by both sources, not scored) | {int(info.n.sum()):,} |
| Overall dataset quality score | {ds['overall']:.3f} / 100 |
| Security-days with a perfect score | {ds['pct_security_days_perfect']:.2f}% |
| Worst day (mean score across securities) | {ds['worst_day']} ({ds['worst_day_score']:.2f}) |

## Issues by type

{_md(counts)}

Lowest-scoring securities:

{_md(worst)}

## Findings

### 1. Vendors disagree on a spin-off adjustment factor (CMCSA)

Reconciliation mismatches were grouped into episodes:

{_md(eps.head(8))}

Long episodes with a nearly constant difference are not noise. They are an
**adjustment-basis disagreement** that ends right before a corporate action:

{_md(ca_links) if len(ca_links) else '_none_'}

Yahoo records the Versant Media spin-off as a 1067:1000 "split" and back-adjusts all earlier
history by 1/1.067. Nasdaq also back-adjusted, but by a factor about 16 bps different. On and
after the ex-date the two sources agree exactly. Neither source is wrong about the actual
prints. They disagree on how to adjust history for a spin-off. This class of issue is easy
to miss without a second source. Blame on this episode: undetermined on
{long_ep.undetermined if long_ep is not None else 0} of {long_ep.days if long_ep is not None else 0}
days (persistence rule). A constant offset is a basis difference, not a bad print on any one
day.

### 2. Nasdaq open outside its own high/low on 2023-06-05 (10 NYSE stocks)

{_md(ex('ohlc_inconsistent', 10))}

On {worst_day} (the worst day in the dataset score), {len(wd)} bars from source(s)
**{wd_src}** have an open outside their own high/low. By listing exchange:
{', '.join(f'{k} {v}' for k, v in wd_ex.items())} (the universe has {n_nyse} NYSE-listed
stocks). Yahoo's bars for the same names that day pass. A single-vendor, single-day defect
confined to NYSE names most likely comes from that vendor's opening-print handling for NYSE
that day. The stocks themselves are not the cause.

### 3. Isolated close mismatch with blame (JNJ, SPY)

Both sources' bars on each isolated (≤3-day) mismatch:

{_md(iso) if len(iso) else '_none_'}

Blame comes from the penalty rule in `docs/CHECKS.md`: distance from the source's own
neighbours, plus whether the close lies outside its own bar or the other source's bar. On JNJ
2023-08-23 (during the Kenvue exchange offer) Nasdaq's close lies outside Yahoo's [low, high]
range, and Nasdaq's whole bar differs (see the high), so Nasdaq is blamed. An `undetermined`
result means the evidence does not separate the two sources.

### 4. Missing field

{_md(ex('missing_field'))}

### 5. Corroborated (info) flags: genuine events, kept but not scored

{_md(info)}

For example, these MAD outlier flags fired identically on both independent sources with no
price disagreement. They are large moves that partly reversed the next day (e.g. earnings):

{_md(ex('outlier_mad', 6))}

## Corporate-action verification

Every declared split, checked in both sources. A correctly adjusted series has an
ex-date move of about 1. The reconstructed raw series should move by about 1/ratio.

{_md(sv)}

Dividend-adjustment check (Yahoo adj_close vs declared dividends):
**{int(counts[counts.check_name.isin(['dividend_adjustment_mismatch', 'unexplained_adjustment'])].n.sum())}**
mismatches over {int(len(ca[ca.action_type == 'dividend'])):,} declared dividends.
"""
    (config.REPORTS_DIR / "QUALITY_REPORT.md").write_text(md, encoding="utf-8")
    return md


def main():
    con = store.connect(config.DB_PATH, read_only=True)
    config.REPORTS_DIR.mkdir(exist_ok=True)
    write_profile(con)
    write_quality(con)
    con.close()
    print("wrote reports/DATA_PROFILE.md, reports/QUALITY_REPORT.md")
